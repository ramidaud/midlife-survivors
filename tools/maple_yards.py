"""Builds the Maple Hollow yard layouts (src/data/maple-yards.js) from the Codex manifests.
Nov 12, 2026. Positions are top-left inside a 416 x 448 yard. Footprints come from the art manifests.
Run from the repo root: python3 tools/maple_yards.py assets/stage/home/v4/yard/manifest-batch-b.json assets/stage/home/v4/yard/manifest-batch-c.json
Checks: no solid footprint in the gate lane (y 200-310) or the right return (x 320-416, y 320-448)."""
import json, sys
from PIL import Image
D = "assets/stage/home/v4/yard/"
MAN = {}
for path in sys.argv[1:] or []:
    for p in json.load(open(path))["pieces"]: MAN[p["id"]] = p
LANE = (0, 200, 416, 110); RET = (320, 320, 96, 128)
def hit(a, b): return a[0] < b[0] + b[2] and b[0] < a[0] + a[2] and a[1] < b[1] + b[3] and b[1] < a[1] + a[3]

def piece(pid, x, y, kind=None, depth=None):
    m = MAN.get(pid, {}); w, h = Image.open(D + pid + "-v4.png").size
    k = kind or ("over" if m.get("drawLayer") == "overhead" else "flat" if m.get("kind") == "WALK-THROUGH" else "wall")
    fp = [[x + a, y + b, c, d] for a, b, c, d in m.get("footprints", [])] if k == "wall" else []
    foot = m.get("footPoint", [w // 2, h - 1])
    out = {"f": pid + "-v4.png", "x": x, "y": y, "k": k, "d": depth if depth is not None else y + foot[1]}
    if fp: out["fp"] = fp
    return out

def frame(row_top_shrubs=True):
    P = []
    for fx in (-24, 376):  # side fences: the spine sits at x 8 and x 408, over the invisible fence walls
        for fy in (40, 104, 144, 304, 368, 384): P.append(piece("wood-vertical", fx, fy, "stand"))
    for i, sx in enumerate((4, 82, 266, 340)):  # top hedge shrubs, leaving the steps (x 162-258) open
        P.append(piece("autumn-shrub-" + "abc"[i % 3], sx, -20, "stand"))
    for i, sx in enumerate((16, 98, 180)):      # bottom shrubs (solid), right return left open
        P.append(piece("autumn-shrub-" + "cab"[i % 3], sx, 386))
    return P

